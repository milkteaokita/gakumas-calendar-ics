def split(source: Path, outdir: Path, *, base_url: str, today: date | None = None) -> list[dict]:
    today = today or datetime.now(JST).date()
    if not source.exists():
        raise FileNotFoundError(f"找不到 {source}，先上传总日历 calendar.ics 到仓库根目录")
    outer, events, _ = read_calendar(source)
    by_cast: dict[str, list[list[str]]] = defaultdict(list)
    no_cast = 0
    expired = 0
    for event in events:
        if not is_current_or_future(event, today):
            expired += 1
            continue
        casts = extract_casts(event)
        if not casts:
            no_cast += 1
            continue
        for cast in casts:
            by_cast[cast].append(event)

    # Keep the existing subscription URL for an actor even if they currently
    # have no upcoming events. A zero-event VCALENDAR is valid and preferable
    # to turning a user's existing Google Calendar subscription into a 404.
    previous_casts: set[str] = set()
    previous_index = outdir / "index.json"
    if previous_index.is_file():
        try:
            previous = json.loads(previous_index.read_text(encoding="utf-8"))
            previous_casts = {item["name"] for item in previous.get("casts", [])
                              if isinstance(item.get("name"), str) and item["name"]}
        except (ValueError, KeyError, TypeError):
            raise ValueError("旧的 casts/index.json 无法读取；为防止误删订阅日历，已中止")
    # If the source contains no cast labels at all, the input may have changed
    # format; refuse to silently publish empty casts. If we have previously
    # valid casts, we can still publish their empty feeds after events expire.
    if not by_cast and not previous_casts:
        raise ValueError(
            "没有找到带有『出演者: 姓名』的今天及未来活动，未覆盖旧日历。"
            "请检查 calendar.ics 的 DESCRIPTION 是否包含出演者字段。"
        )
    for cast in previous_casts:
        by_cast.setdefault(cast, [])
    if outdir.resolve() == source.parent.resolve():
        raise ValueError("输出必须是独立的 casts/ 子目录，避免删除总日历")
    base = base_url.rstrip("/")
    manifest = []
    temp = Path(tempfile.mkdtemp(prefix=".casts_build_", dir=outdir.parent))
    try:
        for cast in sorted(by_cast):
            filename = "cast-" + sha256(cast.encode("utf-8")).hexdigest()[:16] + ".ics"
            data = make_calendar(outer, by_cast[cast], cast)
            (temp / filename).write_bytes(data)
            meta = CHARACTER_MAP.get(cast, {})
            item_entry = {
                "name": cast,
                "count": len(by_cast[cast]),
                "file": filename,
                "url": f"{base}/casts/{filename}" if base else f"/casts/{filename}",
            }
            if meta:
                item_entry["character_tw"] = meta["tw"]
                item_entry["character_cn"] = meta["cn"]
                item_entry["color"] = meta["color"]
            manifest.append(item_entry)
        (temp / "index.json").write_text(json.dumps({
            "source": "calendar.ics", "generated_for_date_jst": today.isoformat(),
            "source_event_count": len(events), "excluded_expired": expired,
            "excluded_without_cast": no_cast, "casts": manifest
        }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        html = render_casts_html(manifest, today)
        (temp / "index.html").write_text(html, encoding="utf-8")
        # Replace entire managed directory only after a valid build.
        backup = outdir.with_name(outdir.name + ".previous")
        if backup.exists():
            shutil.rmtree(backup)
        if outdir.exists():
            outdir.rename(backup)
        try:
            temp.rename(outdir)
        except Exception:
            if backup.exists() and not outdir.exists():
                backup.rename(outdir)
            raise
        if backup.exists():
            shutil.rmtree(backup)
    finally:
        if temp.exists():
            shutil.rmtree(temp)
    print(f"读取总日历 {len(events)} 项；排除过期 {expired} 项；无出演者 {no_cast} 项。")
    print(f"生成 {len(manifest)} 位声优的独立 ICS，合计 {sum(x['count'] for x in manifest)} 条声优-活动关联。")
    print(f"索引：{outdir / 'index.html'}")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description="从学マス calendar.ics 自动拆分每位出演声优的独立 ICS")
    parser.add_argument("--input", type=Path, default=Path("calendar.ics"))
    parser.add_argument("--output-dir", type=Path, default=Path("casts"))
    parser.add_argument("--base-url", default=BASE_URL)
    args = parser.parse_args()
    try:
        args.output_dir.parent.mkdir(parents=True, exist_ok=True)
        split(args.input, args.output_dir, base_url=args.base_url)
    except Exception as exc:
        print(f"拆分失败：{exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
